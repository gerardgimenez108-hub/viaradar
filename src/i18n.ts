export const LANGUAGE = { EN: "en", ES: "es" } as const;
export type Language = typeof LANGUAGE[keyof typeof LANGUAGE];
export const PREFERENCE = { AUTO: "auto", ...LANGUAGE } as const;
export type LanguagePreference = typeof PREFERENCE[keyof typeof PREFERENCE];
export const LANGUAGE_STORAGE_KEY = "viaradar.language";
export interface PreferenceStorage { getItem(key: string): string | null; setItem(key: string, value: string): void; removeItem(key: string): void }
export function readPreference(storage?: PreferenceStorage): LanguagePreference {
  try { const value = storage?.getItem(LANGUAGE_STORAGE_KEY); return value === "en" || value === "es" ? value : "auto"; } catch { return "auto"; }
}
export function savePreference(preference: LanguagePreference, storage?: PreferenceStorage): void {
  try { if (preference === "auto") storage?.removeItem(LANGUAGE_STORAGE_KEY); else storage?.setItem(LANGUAGE_STORAGE_KEY, preference); } catch { /* Storage can be blocked; in-session switching still works. */ }
}
export function resolveLanguage(preference: LanguagePreference, languages: readonly string[]): Language {
  if (preference !== "auto") return preference;
  for (const tag of languages) { const base = tag.toLowerCase().split(/[-_]/)[0]; if(base === "en" || base === "es") return base; }
  return "en";
}

export function translate(language: Language, key: MessageKey, values: Record<string, string | number> = {}): string {
  return (language === "es" ? es[key] : en[key]).replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
}
export function locale(language: Language): string { return language === "es" ? "es-ES" : "en-GB"; }
export function formatTime(language: Language, iso: string): string { return new Intl.DateTimeFormat(locale(language), {timeZone:"Europe/Madrid",hour:"2-digit",minute:"2-digit"}).format(new Date(iso)); }
export function formatTimestamp(language: Language, iso: string): string { return new Intl.DateTimeFormat(locale(language), {timeZone:"Europe/Madrid",dateStyle:"medium",timeStyle:"medium"}).format(new Date(iso)); }
export function formatNumber(language: Language, value: number): string { return new Intl.NumberFormat(locale(language)).format(value); }
export function formatPercent(language: Language, value: number): string { return new Intl.NumberFormat(locale(language), {style:"percent",maximumFractionDigits:0}).format(value); }
